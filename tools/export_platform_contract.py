"""Generate/check the independent package's complete semantic API index."""
import argparse
import json
from pathlib import Path

from up_platform.contracts import build_contract

ROOT = Path(__file__).resolve().parents[1]


def markdown(contract):
    lines = ["# Platform API Index", "", "Generated by `python tools/export_platform_contract.py --write`.",
             "Semantic source: `up_platform/contracts.py`; ABI baseline: `common/legacy_contract.json`.",
             "Registration, dependency availability, execution and hardware validation are distinct.", "",
             "## Entry Points", "", "| API | Signature |", "| --- | --- |"]
    lines.extend("| `{}` | `{}` |".format(item["name"], item["signature"]) for item in contract["entry_points"])
    lines += ["", "## Runtime Migration (31 Members)", "", "| Member | New Owner | Contract |", "| --- | --- | --- |"]
    lines.extend("| `{}` | {} | {} |".format(item["signature"], item["owner"], item["contract"])
                 for item in contract["runtime"])
    lines += ["", "## Execution Interfaces", ""]
    for purpose, methods in contract["execution_interfaces"].items():
        lines.append("### " + purpose)
        lines.extend("- `{}{}`".format(name, signature) for name, signature in methods.items())
        lines.append("")
    lines += ["## Operations (73)", "", "`common` is explicitly reusable by both purposes; it is not a CPU fallback.", ""]
    for item in contract["operations"]:
        lines += ["### " + item["name"], "", "```python", item["signature"], "```", "",
                  "- Scope: `{}`; purposes: {}.".format(item["scope"], ", ".join(item["purposes"])),
                  "- Inputs: " + item["inputs"], "- Result: " + item["returns"],
                  "- Device/layout: " + item["device_and_layout"], "- Empty input: " + item["empty_input"],
                  "- State: " + item["state_updates"], "- Gradient: " + item["gradients"],
                  "- Export: " + item["export"],
                  "- Dtype/variants/dependencies: " + json.dumps(item["registered_providers"], sort_keys=True), ""]
    return "\n".join(lines).rstrip() + "\n"


def outputs(root=ROOT):
    contract = build_contract()
    return {root / "docs/platform/interface_contract.json": json.dumps(contract, indent=2, sort_keys=True) + "\n",
            root / "docs/platform/API_INDEX.md": markdown(contract)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, value in outputs().items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value, encoding="utf-8", newline="\n")
        elif not path.exists() or path.read_text(encoding="utf-8") != value:
            stale.append(path.relative_to(ROOT).as_posix())
    if stale:
        print("Stale platform contracts: " + ", ".join(stale))
        return 1
    print("Platform contract: 31 migrated runtime members, 73 operations; no drift")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
